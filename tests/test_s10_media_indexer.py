class TestS10MediaIndexer(unittest.TestCase):
    def test_s10_t1_vfr_2997_30_60_and_rotation_rational_mapping(self) -> None:
        """S10.T1: CFR/VFR, 29.97/30/60 fps sources and rotation give exact rational frame boundaries."""
        # 1) 29.97 fps NTSC (timebase 1001/30000): 30 frames (~1.001s)
        raw_2997 = [{"frame_id": i, "pts": i * 1001, "duration_pts": 1001} for i in range(30)]
        idx_2997 = validate_and_build_pts_index(raw_2997, 1, 30000)
        cmap_2997 = build_vfr_to_cfr24_map(
            idx_2997,
            source_revision_id="rev-2997",
            source_start_sec=Fraction(0, 1),
            timeline_frame_count=24,
            rotation_degrees=90,
        )
        self.assertEqual(cmap_2997.profile_id, MEDIA_PROFILE_ID)
        self.assertEqual(cmap_2997.timeline_frame_count, 24)
        self.assertEqual(cmap_2997.rotation_degrees, 90)
        self.assertGreater(len(cmap_2997.dropped_source_frame_ids), 0)
        self.assertFalse(cmap_2997.native_conform_allowed)

        # 2) True VFR stream (variable durations in 1/90000 MPEG-TS timebase)
        vfr_durations = [3000, 4500, 6000, 2250, 3750, 3000, 4500, 3000, 6000, 3000]
        raw_vfr = []
        curr_pts = 0
        for fid, d in enumerate(vfr_durations):
            raw_vfr.append({"frame_id": fid, "pts": curr_pts, "duration_pts": d})
            curr_pts += d
        idx_vfr = validate_and_build_pts_index(raw_vfr, 1, 90000)
        cmap_vfr = build_vfr_to_cfr24_map(
            idx_vfr,
            source_revision_id="rev-vfr",
            source_start_sec=Fraction(0, 1),
            timeline_frame_count=8,
            rotation_degrees=-90,
        )
        self.assertEqual(cmap_vfr.rotation_degrees, 270)
        # Verify frame 2 (duration 6000/90000 = 1/15s > 1/24s) is repeated in 24fps timeline
        self.assertIn(2, cmap_vfr.repeated_source_frame_ids)

    def test_s10_t1_real_ffmpeg_probed_video_indexing(self) -> None:
        """S10.T1: Real video generated by ffmpeg and probed via ffprobe builds verified PTS index & detects untagged/silent streams."""
        with tempfile.TemporaryDirectory() as tmpdir:
            # 1) Untagged & silent video -> color_decision is unsupported_needs_decision (no silent bt709 default!) and has_audio_stream is False
            untagged_path = Path(tmpdir) / "test_untagged_24fps.mp4"
            subprocess.run(
                [
                    "ffmpeg",
                    "-y",
                    "-f",
                    "lavfi",
                    "-i",
                    "color=c=blue:s=320x240:r=24:d=1",
                    "-pix_fmt",
                    "yuv420p",
                    str(untagged_path),
                ],
                check=True,
                capture_output=True,
                timeout=15,
            )
            probed_untagged = probe_and_index_real_video(untagged_path)
            self.assertEqual(probed_untagged["frame_count"], 24)
            self.assertFalse(probed_untagged["has_audio_stream"])
            self.assertEqual(probed_untagged["color_decision"]["status"], "unsupported_needs_decision")

            # 2) Properly tagged Rec.709 video -> sdr_passthrough_or_transform
            video_path = Path(tmpdir) / "test_24fps_bt709.mp4"
            cmd = [
                "ffmpeg",
                "-y",
                "-f",
                "lavfi",
                "-i",
                "color=c=blue:s=320x240:r=24:d=1",
                "-c:v",
                "libx264",
                "-pix_fmt",
                "yuv420p",
                "-x264-params",
                "colorprim=bt709:transfer=bt709:colormatrix=bt709",
                "-color_primaries",
                "bt709",
                "-color_trc",
                "bt709",
                "-colorspace",
                "bt709",
                str(video_path),
            ]
            subprocess.run(cmd, check=True, capture_output=True, timeout=15)
            probed = probe_and_index_real_video(video_path)
            self.assertEqual(probed["frame_count"], 24)
            self.assertEqual(probed["width"], 320)
            self.assertEqual(probed["height"], 240)
            self.assertEqual(probed["color_decision"]["status"], "sdr_passthrough_or_transform")

    def test_s10_t2_critical_evidence_flash_frame_drop_blocked(self) -> None:
        """S10.T2: Short flash frame containing critical evidence dropped by 60->24 conform is detected & blocked."""
        # 60 fps source (duration_pts = 1, timebase = 1/60):
        # Timeline frame k=0 samples midpoint t(0) = 1/48s = 1.25/60s -> selects source frame 1 ([1/60, 2/60))
        # Source frame 0 ([0, 1/60)) is NOT selected at k=0!
        raw_60 = [
            {
                "frame_id": i,
                "pts": i,
                "duration_pts": 1,
                "has_critical_evidence": (i == 0),  # Frame 0 has a 16.6ms flash sign
                "evidence_tag": "road_sign_flash" if i == 0 else None,
            }
            for i in range(60)
        ]
        idx_60 = validate_and_build_pts_index(raw_60, 1, 60)

        with self.assertRaises(MediaMappingError) as ctx:
            build_vfr_to_cfr24_map(
                idx_60,
                source_revision_id="rev-60fps-flash",
                source_start_sec=Fraction(0, 1),
                timeline_frame_count=24,
                enforce_critical_evidence_preservation=True,
            )
        self.assertIn("S10.T2 violation", str(ctx.exception))
        self.assertIn("0", str(ctx.exception))

    def test_s10_t3_audio_48khz_sync_drift_and_sdr_hdr_color_policy(self) -> None:
        """S10.T3: Audio 48kHz ties-to-even mapping, negative PTS offset preservation, drift check & HDR/SDR policy."""
        # Negative audio start PTS (-480 samples at 48kHz = -10.0 ms offset, within 41.67 ms MEDIA-04 tolerance)
        amap_ok = compute_canonical_audio_mapping(
            source_sample_rate=48000,
            source_start_pts=-480,
            source_duration_pts=480000,
            time_base_num=1,
            time_base_den=48000,
            video_start_sec=Fraction(0, 1),
            measured_end_offset_ms=-5.0,
        )
        self.assertEqual(amap_ok.canonical_sample_rate, CANONICAL_AUDIO_SAMPLE_RATE)
        self.assertEqual(amap_ok.canonical_start_sample, -480)
        self.assertAlmostEqual(amap_ok.av_offset_ms, -10.0, places=3)
        self.assertAlmostEqual(amap_ok.av_sync_drift_ms, 5.0, places=3)
        self.assertTrue(amap_ok.within_media04_tolerance)

        # Excessive drift (65 ms > 41.67 ms) -> flagged out of tolerance
        amap_bad = compute_canonical_audio_mapping(
            source_sample_rate=44100,
            source_start_pts=0,
            source_duration_pts=441000,
            time_base_num=1,
            time_base_den=44100,
            video_start_sec=Fraction(0, 1),
            measured_end_offset_ms=65.0,
        )
        self.assertFalse(amap_bad.within_media04_tolerance)

        # Color Profile evaluation:
        # 1) Unknown color tags -> unsupported_needs_decision
        c_unknown = evaluate_color_profile(None, "bt709", "bt709")
        self.assertEqual(c_unknown.status, "unsupported_needs_decision")

        # 2) HDR without validated fixture -> unsupported_needs_decision
        c_hdr_unval = evaluate_color_profile(
            "bt2020", "smpte2084", "bt2020nc", has_validated_hdr_tonemap_fixture=False
        )
        self.assertEqual(c_hdr_unval.status, "unsupported_needs_decision")

        # 3) HDR with validated fixture -> linear zscale + Mobius tonemap to Rec.709
        c_hdr_ok = evaluate_color_profile(
            "bt2020", "smpte2084", "bt2020nc", has_validated_hdr_tonemap_fixture=True
        )
        self.assertEqual(c_hdr_ok.status, "hdr_tonemap_validated")
        self.assertIn("tonemap=mobius", c_hdr_ok.ffmpeg_filter_chain or "")

    def test_s10_t4_seek_to_source_and_resolve_half_open_boundary_conversion(self) -> None:
        """S10.T4: Seek from timeline frame uses exact VFR conform map and Resolve boundary conversion is exact."""
        in_f, out_inc = convert_half_open_to_resolve_inclusive(100, 340)
        self.assertEqual(in_f, 100)
        self.assertEqual(out_inc, 339)

        raw = [{"frame_id": i, "pts": i * 1000, "duration_pts": 1000} for i in range(48)]
        idx = validate_and_build_pts_index(raw, 1, 24000)
        cmap = build_vfr_to_cfr24_map(
            idx,
            source_revision_id="rev-seek",
            source_start_sec=Fraction(10, 24),
            timeline_frame_count=12,
        )
        src_fid, src_pts = cmap.seek_source_from_timeline(5)
        self.assertEqual(src_fid, 15)
        self.assertEqual(src_pts, 15000)

    def test_s10_3_real_proxy_generation_and_hash_mapping(self) -> None:
        """S10.3: Generates a real CFR 24fps SDR proxy video and verifies source->proxy SHA-256 and PTS mapping."""
        with tempfile.TemporaryDirectory() as tmpdir:
            src_video = Path(tmpdir) / "source_30fps.mp4"
            proxy_video = Path(tmpdir) / "proxy_24fps.mp4"
            subprocess.run(
                [
                    "ffmpeg",
                    "-y",
                    "-f",
                    "lavfi",
                    "-i",
                    "testsrc=duration=1:size=640x360:rate=30",
                    "-f",
                    "lavfi",
                    "-i",
                    "sine=frequency=440:duration=1",
                    "-c:v",
                    "libx264",
                    "-pix_fmt",
                    "yuv420p",
                    "-x264-params",
                    "colorprim=bt709:transfer=bt709:colormatrix=bt709",
                    "-color_primaries",
                    "bt709",
                    "-color_trc",
                    "bt709",
                    "-colorspace",
                    "bt709",
                    "-c:a",
                    "aac",
                    str(src_video),
                ],
                check=True,
                capture_output=True,
                timeout=20,
            )
            proxy_artifact = generate_proxy_and_mapping(
                source_video_path=src_video,
                proxy_output_path=proxy_video,
                source_revision_id="rev-s10-proxy-test",
                target_height=180,
            )
            self.assertTrue(Path(proxy_artifact.proxy_path).is_file())
            self.assertEqual(len(proxy_artifact.source_sha256), 64)
            self.assertEqual(len(proxy_artifact.proxy_sha256), 64)
            self.assertNotEqual(proxy_artifact.source_sha256, proxy_artifact.proxy_sha256)
            self.assertEqual(proxy_artifact.proxy_height, 180)
            self.assertEqual(proxy_artifact.conform_map.timeline_frame_count, 24)
            src_fid, _ = proxy_artifact.conform_map.seek_source_from_timeline(0)
            self.assertIn(src_fid, (0, 1))


